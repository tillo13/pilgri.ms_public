def get_fomo_greeting(user_id: int, last_login_str: str) -> str:
    """Get a rotating greeting phrase based on user_id for consistency."""
    import random
    # Use user_id as seed for consistent phrase per user
    random.seed(user_id)
    phrase = random.choice(FOMO_GREETING_PHRASES)
    random.seed()  # Reset seed
    return f"{phrase} <strong style='color: #ffcccc;'>{last_login_str}</strong>"

def get_fomo_closing(user_id: int) -> tuple:
    """Get a rotating closing phrase (header, description) based on user_id."""
    import random
    random.seed(user_id)
    header, desc = random.choice(FOMO_CLOSING_PHRASES)
    random.seed()
    return header, desc

