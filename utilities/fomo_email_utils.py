def generate_fomo_email_data(user_id: int, secret_key: str = None) -> Dict:
    """
    Generate all data needed for a FOMO email.

    Returns dict with:
        - user: Basic user info
        - fomo_data: Full FOMO data from postgres_utils
        - pending_items: Summary of pending items
        - action_links: One-click action URLs (if secret_key provided)
        - video_data: Video thumbnail/URL data (if user has video)
        - days_away: Days since last login
    """
    # Get user info
    user = get_user_by_id(user_id)
    if not user:
        return {'error': f'User {user_id} not found'}

    # Get FOMO data
    fomo_data = get_user_fomo_data(user_id)
    if not fomo_data:
        return {'error': f'Could not get FOMO data for user {user_id}'}

    # Calculate next goal
    try:
        from tools.send_notifications import calculate_next_goal
        next_goal = calculate_next_goal(
            fomo_data.get('current_balance', 0),
            fomo_data.get('owned_upgrades', []),
            fomo_data.get('owned_infrastructure', {})
        )
        fomo_data['next_goal'] = next_goal
    except Exception as e:
        logger.warning(f"Could not calculate next goal: {e}")

    # Build pending items summary
    pending_items = {
        'expeditions': fomo_data.get('expedition_stats', {}).get('completed', 0),
        'discoveries': fomo_data.get('pending_discoveries_count', 0),
        'sepolia': fomo_data.get('infrastructure_generated', 0),
    }

    # Generate action links if secret key provided
    action_links = None
    if secret_key:
        action_links = generate_action_links(user_id, secret_key)

    # Calculate days away
    days_away = calculate_days_away(fomo_data.get('last_login'))

    # Get video data
    commander = fomo_data.get('commander')
    commander_name = commander.get('name') if commander else user.get('given_name') or user.get('name')
    video_data = get_user_video_data(user_id, commander_name)

    return {
        'user': user,
        'fomo_data': fomo_data,
        'pending_items': pending_items,
        'action_links': action_links,
        'video_data': video_data,
        'days_away': days_away,
        'user_name': user.get('given_name') or user.get('name') or 'Commander',
    }


def send_fomo_email_to_user(
    user_id: int,
    secret_key: str = None,
    test_mode: bool = False,
    test_recipient: str = "andy.tillo@gmail.com"
) -> Dict:
    """
    Generate and send a FOMO email to a user (or test recipient).

    Args:
        user_id: The user to generate the email for
        secret_key: Secret key for action links (optional)
        test_mode: If True, send to test_recipient instead of real user
        test_recipient: Email to send to in test mode

    Returns:
        Dict with 'success', 'message', and email details
    """
    # Generate all email data
    email_data = generate_fomo_email_data(user_id, secret_key)

    if 'error' in email_data:
        return {'success': False, 'message': email_data['error']}

    # Determine recipient
    user = email_data['user']
    to_email = test_recipient if test_mode else user.get('email')

    # Modify name in test mode to indicate it's a preview
    user_name = email_data['user_name']
    if test_mode:
        user_name = f"[PREVIEW: {user.get('email')}] {user_name}"

    # Send the email
    success = send_welcome_back_email(
        to_email=to_email,
        user_name=user_name,
        days_away=email_data['days_away'],
        pending_items=email_data['pending_items'],
        fomo_data=email_data['fomo_data'],
        action_links=email_data['action_links'],
        video_data=email_data['video_data']
    )

    return {
        'success': success,
        'message': f"Email {'sent' if success else 'failed'} to {to_email}",
        'to_email': to_email,
        'user_id': user_id,
        'has_video': email_data['video_data'] is not None,
        'pending_discoveries': email_data['pending_items'].get('discoveries', 0),
        'pending_sepolia': email_data['pending_items'].get('sepolia', 0),
        'days_away': email_data['days_away'],
    }
